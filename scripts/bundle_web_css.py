#!/usr/bin/env python3
"""Bundle web/ stylesheets so each page makes one render-blocking CSS request (r4, Proof r3 P3-5).

Sources stay the files you edit; the bundles are generated and committed:
  web/css/demo.bundle.css  <- vendor/fonts/fonts.css, css/tokens.css, styles.css, css/chrome.css,
                              css/demo-bridge.css   (demo.html; leaflet.css loads with leaflet.js, see app.js)
  web/css/site.bundle.css  <- vendor/fonts/fonts.css, css/tokens.css, css/chrome.css, css/site.css
                                                    (index, how-it-works, model, about; 404.html keeps its links)
Relative url(...) references are rewritten so they resolve from web/css/.
Usage:  python3 scripts/bundle_web_css.py [WEB_DIR]   (default: web)   ·   --check exits 1 if a bundle is stale.
"""
import os, re, sys

BUNDLES = {
    "css/demo.bundle.css": ["vendor/fonts/fonts.css", "css/tokens.css", "styles.css", "css/chrome.css",
                            "css/demo-bridge.css"],
    "css/site.bundle.css": ["vendor/fonts/fonts.css", "css/tokens.css", "css/chrome.css", "css/site.css"],
}
URL = re.compile(r"""url\(\s*(['"]?)([^'")]+)\1\s*\)""")


def rebase(css, src, out):
    src_dir, out_dir = os.path.dirname(src), os.path.dirname(out)

    def fix(m):
        q, ref = m.group(1), m.group(2)
        if re.match(r"^(data:|https?:|/|#)", ref):
            return m.group(0)
        return "url(%s%s%s)" % (q, os.path.relpath(os.path.normpath(os.path.join(src_dir, ref)), out_dir).replace(os.sep, "/"), q)
    return URL.sub(fix, css)


def minify(css):
    """Drop comments and indentation/blank lines; strings are copied byte-for-byte. No other rewriting."""
    out, i, n = [], 0, len(css)
    while i < n:
        c = css[i]
        if c in "\"'":
            j = i + 1
            while j < n and css[j] != c:
                j += 2 if css[j] == "\\" else 1
            out.append(css[i:j + 1]); i = j + 1
        elif css.startswith("/*", i):
            j = css.find("*/", i + 2); i = n if j < 0 else j + 2
        elif c in " \t\r\n":
            j = i
            while j < n and css[j] in " \t\r\n":
                j += 1
            prev = out[-1][-1:] if out else ""
            nxt = css[j:j + 1]
            if prev and nxt and prev not in "{};,>\n" and nxt not in "{};,":
                out.append(" ")
            i = j
        else:
            out.append(c); i += 1
    return "".join(out)


def build(web):
    out = {}
    for name, parts in BUNDLES.items():
        chunks = ["/* GENERATED by scripts/bundle_web_css.py from %s. Edit the sources, then re-run. */" % ", ".join(parts)]
        for part in parts:
            with open(os.path.join(web, part), encoding="utf-8") as fh:
                chunks.append(minify(rebase(fh.read(), part, name)))
        out[name] = "\n".join(chunks) + "\n"
    return out


def main():
    args = [a for a in sys.argv[1:] if a != "--check"]
    web = args[0] if args else "web"
    stale = []
    for name, text in build(web).items():
        path = os.path.join(web, name)
        cur = open(path, encoding="utf-8").read() if os.path.exists(path) else None
        if cur != text:
            stale.append(name)
            if "--check" not in sys.argv:
                with open(path, "w", encoding="utf-8") as fh:
                    fh.write(text)
    if "--check" in sys.argv and stale:
        print("stale:", ", ".join(stale)); sys.exit(1)
    print(("rebuilt: " + ", ".join(stale)) if stale else "bundles up to date")


if __name__ == "__main__":
    main()
